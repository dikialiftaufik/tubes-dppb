class MenuItem {
  final String id;
  final String name;
  final String category;
  final String meat;
  final int price;
  final String description;
  final String imageUrl;

  MenuItem({
    required this.id,
    required this.name,
    required this.category,
    required this.meat,
    required this.price,
    required this.description,
    required this.imageUrl,
  });
}